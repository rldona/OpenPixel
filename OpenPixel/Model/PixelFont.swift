import Foundation

/// A bitmap font drawn pixel by pixel, so text stays crisp at any integer scale.
/// Glyphs are rows of `#` (ink) and `.` (empty), bottom-aligned on the
/// baseline; `descent` rows hang below it (g, p, comma…).
struct PixelFont: Identifiable, Sendable {
    struct Glyph: Sendable {
        var rows: [String]
        var descent = 0

        var width: Int { rows.map(\.count).max() ?? 0 }
        var ascent: Int { rows.count - descent }
    }

    let id: String
    let name: String
    let glyphs: [Character: Glyph]
    /// Advance of a space, in pixels.
    let spaceWidth: Int
    /// Lowercase letters fall back to uppercase (fonts without lowercase).
    let uppercaseOnly: Bool

    var ascent: Int { glyphs.values.map(\.ascent).max() ?? 0 }
    var descent: Int { glyphs.values.map(\.descent).max() ?? 0 }

    /// The glyph for a character, falling back to its plain letter
    /// (é → e), its other case, and finally "?".
    func glyph(for character: Character) -> Glyph? {
        if character == " " { return nil }
        let plain = String(character).folding(options: .diacriticInsensitive, locale: nil).first ?? character
        // `first` keeps single characters when case mapping gives several (ß → SS).
        func upper(_ c: Character) -> Character { c.uppercased().first ?? c }
        func lower(_ c: Character) -> Character { c.lowercased().first ?? c }
        var candidates = [character, plain, upper(character), upper(plain), lower(character), lower(plain)]
        if uppercaseOnly { candidates.insert(contentsOf: [upper(character), upper(plain)], at: 0) }
        for c in candidates { if let g = glyphs[c] { return g } }
        return glyphs["?"]
    }

    static let all: [PixelFont] = [.standard, .tiny]

    static func named(_ id: String) -> PixelFont? { all.first { $0.id == id } }
}

// MARK: - Building glyphs

private extension PixelFont.Glyph {
    init(_ rows: String..., descent: Int = 0) {
        self.init(rows: rows, descent: descent)
    }

    /// The glyph with an accent `mark` (rows of the same kind) on top, centered.
    func accented(_ mark: [String]) -> PixelFont.Glyph {
        let w = width
        let centered = mark.map { row -> String in
            let pad = max(0, (w - row.count) / 2)
            return String(repeating: ".", count: pad) + row + String(repeating: ".", count: max(0, w - row.count - pad))
        }
        return PixelFont.Glyph(rows: centered + rows, descent: descent)
    }

    /// Turned 180° (¿ from ?, ¡ from !), hanging below the baseline.
    func turned(descent: Int) -> PixelFont.Glyph {
        PixelFont.Glyph(rows: rows.reversed().map { String($0.reversed()) }, descent: descent)
    }
}

private enum Mark {
    static let acute = ["..#", ".#."]
    static let grave = [".#.", "..#"]
    static let circumflex = [".#.", "#.#"]
    static let diaeresis = ["#.#", "..."]
    static let tilde = [".##.#", "#..#."]
}

